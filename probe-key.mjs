import { connectCdp, sleep } from './verify-cdp.mjs';
const page = await connectCdp({ port: 9334 });
await page.evaluate('location.reload()');
await sleep(1200);
await page.waitFor(`document.body.dataset.readmepdfInit === '1'`);
await page.evaluate(`document.getElementById('sample-btn').focus()`);
console.log('active', await page.evaluate('document.activeElement.id'));
await page.send('Input.dispatchKeyEvent', { type: 'rawKeyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, nativeVirtualKeyCode: 13 });
await page.send('Input.dispatchKeyEvent', { type: 'char', key: 'Enter', code: 'Enter', text: '\r', windowsVirtualKeyCode: 13 });
await page.send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, nativeVirtualKeyCode: 13 });
await sleep(500);
console.log('h1', await page.evaluate(`document.querySelector('#preview-doc h1')?.textContent ?? null`));
console.log('toc', await page.evaluate(`document.getElementById('toc-toggle').checked`));
await page.evaluate(`document.getElementById('toc-toggle').focus()`);
await page.send('Input.dispatchKeyEvent', { type: 'rawKeyDown', key: ' ', code: 'Space', windowsVirtualKeyCode: 32, nativeVirtualKeyCode: 32 });
await page.send('Input.dispatchKeyEvent', { type: 'keyUp', key: ' ', code: 'Space', windowsVirtualKeyCode: 32, nativeVirtualKeyCode: 32 });
await sleep(300);
console.log('toc after space', await page.evaluate(`document.getElementById('toc-toggle').checked`));
page.close();
